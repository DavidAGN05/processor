module mult_tb();
  
  reg [7:0] a = 0;
  reg [7:0] b = 0;
  wire [15:0] q;
  
  mult uut(
    .a(a),
    .b(b),
    .q(q)
  );
  
  initial begin
    $dumpfile("dump.vcd");
    $dumpvars;
    
    // 0*0
    a = 8'b0; b = 8'b0;
    // 0*1
    #1 a = 8'b0; b = 8'b0000_0001;
    // 0 * -1
    #1 a = 8'b0; b = 8'b1111_1111;
    // 1*1
    #1 a = 8'b0000_0001; b = 8'b0000_0001;
    // -1 * -1
    #1 a = 8'b1111_1111; b = 8'b1111_1111;
    // 1 * -1
    #1 a = 8'b0000_0001; b = 8'b1111_1111;
    // 8*7
    #1 a = 8'b0000_1000; b = 8'b0000_0111;
    // -5*10
    #1 a = 8'b1111_1011; b = 8'b0000_1010;
    // -11 * -11
    #1 a = 8'b1111_0101; b = 8'b1111_0101;
    // 127 * -128 (min)
    #1 a = 8'b0111_1111; b = 8'b1000_0000;
    // -128 * -128 (max)
    #1 a = 8'b1000_0000; b = 8'b1000_0000;
    // 127 * 1 (max 8-bit output)
    #1 a = 8'b0111_1111; b = 8'b0000_0001;
    // -16 * 8 (min 8-bit output)
    #1 a = 8'b1111_0000; b = 8'b0000_1000;
    
    #5 $finish;
  end
  
endmodule
