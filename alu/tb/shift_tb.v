module shift_tb();
  
  reg [8:0] a = 0;
  reg [8:0] b = 0;
  wire [8:0] q;
  
  shift uut(
    .a(a),
    .b(b),
    .q(q)
  );
  
  initial begin
    $dumpfile("dump.vcd");
    $dumpvars;
    
    // 1_1111_1111 >> 0 (min shift)
    a = 9'b0; b = 9'b1_1111_1111;
    // 0_0000_0000 >> 2
    #1 a = 9'b0_0000_0010; b = 9'b0_0000_0000;
    // 0_0000_0001 >> 1
    #1 a = 9'b0_0000_0001; b = 9'b0_0000_0001;
    // 1_0000_0000 >> 8
    #1 a = 9'b0_0000_1000; b = 9'b1_0000_0000;
    // 1_0101_0101 >> 3
    #1 a = 9'b0_0000_0011; b = 9'b1_0101_0101;
    // 1_1111_1111 >> 4
    #1 a = 9'b0_0000_0100; b = 9'b1_1111_1111;
    // 1_0001_0001 >> 10
    #1 a = 9'b0_0000_1010; b = 9'b1_0001_0001;
    // 1_1111_1111 >> 511 (max shift)
    #1 a = 9'b1_1111_1111; b = 9'b0_1111_0000;
 
    #5 $finish;
  end
  
endmodule
